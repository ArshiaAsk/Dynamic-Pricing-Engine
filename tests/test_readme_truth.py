"""R23 regression guard: the README must not reference paths that do not exist
and must not resurrect claims that STATE.md/DECISIONS.md record as removed.

Two checks:

(a) ``test_readme_referenced_paths_exist`` — every repo-relative file/script path
    that appears in a README **code span or fenced code block** exists on disk.
    URLs, shell placeholders (``<...>``), globs/shell substitutions (``*``/``$``),
    directory references (trailing ``/``) and a small documented list of
    gitignored *generated* artifacts are ignored.

(b) ``test_readme_has_no_removed_claims`` — a list of phrases that must not
    appear in README.md, each with a one-line reason, built from STATE.md /
    DECISIONS.md facts about modules, scripts, config keys and claim families
    that were deleted or never existed. Matching is case-insensitive on whole
    words (a phrase is bounded by non-alphanumeric characters, so ``aws`` does
    not match ``laws``).

The Markdown *link* targets (e.g. ``docs/API.md``) are deliberately **not**
checked here: R31 owns broken doc links; R23 only keeps the code spans/blocks
honest.

The forbidden-phrase scan **skips the text of the ``## Limitations`` section**.
That section is the one place where stating that something does *not* exist
(e.g. drift detection, authentication) is required, so absence words such as
``drift`` are legitimate there. Everywhere else the check is unchanged.
"""
import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
README = REPO_ROOT / "README.md"

# ---------------------------------------------------------------------------
# (a) path existence
# ---------------------------------------------------------------------------

# Repo-relative path-shaped tokens, with an optional ``./`` prefix. The char
# class intentionally includes ``*`` and ``$`` so that shell globs / command
# substitutions are captured whole and can be filtered out below.
_PATH_RE = re.compile(
    r"(?<![\w./-])(?:\./)?("
    r"(?:src|scripts|tests|configs|models|data|reports|logs|docs|backups|\.agents)"
    r"/[A-Za-z0-9_./*$-]+"
    r"|docker-compose[\w.-]*\.ya?ml"
    r"|Dockerfile[\w.-]*"
    r"|start\.sh|app\.py|requirements\.txt|pytest\.ini|README\.md|AGENTS\.md"
    r")"
)

# Paths that legitimately appear in the README but are *generated* artifacts
# listed in .gitignore, so they need not exist in a fresh checkout. Anything
# not listed here must exist on disk.
IGNORE_PATHS = {
    "models/demand_model.pkl": "generated model artifact, gitignored (.gitignore:51)",
    "reports/training_metrics.json": "generated by training, gitignored (.gitignore:61)",
    "reports/feature_importance.csv": "generated by training, gitignored (.gitignore:60)",
}

_FENCED_RE = re.compile(r"```.*?```", re.DOTALL)
_INLINE_RE = re.compile(r"`([^`\n]+)`")


def _code_text(readme_text: str) -> str:
    """Return only the text inside fenced code blocks and inline code spans."""
    parts = _FENCED_RE.findall(readme_text)
    parts += _INLINE_RE.findall(readme_text)
    return "\n".join(parts)


def _referenced_paths(readme_text: str):
    tokens = []
    for match in _PATH_RE.finditer(_code_text(readme_text)):
        token = match.group(1).rstrip(".,;:)")
        if token not in tokens:
            tokens.append(token)
    return tokens


def test_readme_referenced_paths_exist():
    readme_text = README.read_text(encoding="utf-8")
    missing = []
    for token in _referenced_paths(readme_text):
        if token in IGNORE_PATHS:
            continue
        if token.endswith("/"):  # directory reference (e.g. logs/predictions/)
            continue
        if any(ch in token for ch in "<>$*"):  # placeholder / glob / substitution
            continue
        if not (REPO_ROOT / token).exists():
            missing.append(token)
    assert missing == [], f"README references paths that do not exist: {sorted(missing)}"


# ---------------------------------------------------------------------------
# (b) forbidden phrases
# ---------------------------------------------------------------------------

# (phrase, reason) — every phrase is something STATE.md / DECISIONS.md records as
# removed or never-existing, so it must not reappear in the README.
FORBIDDEN_PHRASES = [
    ("bayesian", "the optimizer method is rejected at the API (D2); no Bayesian library is used"),
    ("backup_database", "scripts/backup_database.sh was deleted (R22/D9)"),
    ("restore_database", "scripts/restore_database.sh was deleted (R22/D9)"),
    ("pre_deploy_check", "scripts/pre_deploy_check.sh does not exist (STATE.md §1)"),
    ("deploy.sh", "scripts/deploy.sh does not exist (STATE.md §1, D19)"),
    ("aws", "no AWS tooling or deployment exists (STATE.md §1, D19)"),
    ("deploy to aws", "no AWS deployment flow exists (D19)"),
    ("ec2", "no AWS EC2 deployment exists (D19)"),
    ("default_method", "the config key pricing.default_method was removed in R18"),
    ("run_hyperparameter_tuning", "the config key training.run_hyperparameter_tuning was removed in R18"),
    ("prometheus", "prometheus-client is not imported and was removed (STATE.md §1)"),
    ("drift", "drift detection was deleted in R15/D13"),
    ("nginx", "the nginx service was removed in R24/D17"),
    ("integrated_optimizer", "src/pricing/integrated_optimizer.py was deleted in R22"),
    ("transformer", "src/features/transformer.py was deleted in R22"),
    ("model_loader", "src/pricing/model_loader.py was deleted in R22"),
    ("sqlite", "the orphaned SQLite app DB and its scripts were removed (R22/D9)"),
    ("retention", "the 7-day retention claim had no consumer (R22/D9)"),
    ("shap", "shap was removed as an unused dependency (R21)"),
    ("model versioning", "MLflow tracking is already used; the registry is an optional promoted path (D8)"),
    ("production-ready", "unbacked adjective — no production evidence in STATE.md"),
    ("production ready", "unbacked adjective — no production evidence in STATE.md"),
    ("enterprise-grade", "unbacked adjective — no production evidence in STATE.md"),
    ("0.49", "stale R² claim; the seeded artifact is R² 0.41930 (STATE.md §1)"),
    ("49%", "stale R² claim; the seeded artifact is R² 0.41930 (STATE.md §1)"),
]


def _find_phrase(text_lower: str, phrase: str):
    pattern = r"(?<![a-z0-9])" + re.escape(phrase.lower()) + r"(?![a-z0-9])"
    return re.search(pattern, text_lower)


_LIMITATIONS_RE = re.compile(
    r"^## Limitations\s*$.*?(?=^## |\Z)", re.MULTILINE | re.DOTALL
)


def _without_limitations(text: str) -> str:
    """Drop the Limitations section: absence statements are legitimate there."""
    return _LIMITATIONS_RE.sub("", text)


def test_readme_has_no_removed_claims():
    text_lower = _without_limitations(README.read_text(encoding="utf-8")).lower()
    offenders = []
    for phrase, reason in FORBIDDEN_PHRASES:
        if _find_phrase(text_lower, phrase):
            offenders.append(f"{phrase!r} ({reason})")
    assert offenders == [], "README contains removed/false claims: " + "; ".join(offenders)
